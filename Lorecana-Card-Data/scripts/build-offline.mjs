import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../dist/',import.meta.url);
const names=['core.mjs','market.mjs','deck-market.mjs','filter-ui.mjs','studio-app.js'];
const catalog=JSON.parse(await readFile(new URL('data/cards.json',root),'utf8'));
let bundle='// Generated by scripts/build-offline.mjs. Edit the source modules instead.\n(()=>{\nconst modules={};\nconst offlineCards='+JSON.stringify(catalog)+';\n';
for(const name of names){
  let source=await readFile(new URL(name,root),'utf8');
  const exports=[...source.matchAll(/^export (?:function|const|let) (\w+)/gm)].map(m=>m[1]);
  source=source.replace(/^import \{([^}]+)\} from '\.\/([^']+)';/gm,(_,bindings,dependency)=>`const {${bindings}}=modules[${JSON.stringify(dependency)}];`);
  source=source.replace(/^export /gm,'');
  if(/^(?:import|export) /m.test(source))throw Error(`Unsupported module syntax: ${name}`);
  bundle+=`modules[${JSON.stringify(name)}]=(()=>{\n${source}\nreturn {${exports.join(',')}};\n})();\n`;
}
bundle+='})();\n';
await writeFile(new URL('offline-app.js',root),bundle);
console.log(`Built offline app with ${catalog.length} cards.`);
